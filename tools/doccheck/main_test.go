package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeTree creates files (path -> contents) under a new temp directory.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestRun(t *testing.T) {
	t.Parallel()
	root := writeTree(t, map[string]string{
		"go.mod": "module example.com/m\n",
		"good/good.go": `// Package good is documented.
package good

// T is a type.
type T[K any] struct{}

// F does nothing.
func F() {}

// M is a method.
func (T[K]) M() {}
`,
		"bad/a.go": `package bad

func f() {}

type T struct{}

func (t *T) m() {}

type G[K, V any] struct{}

func (G[K, V]) n() {}

func (struct{}) odd() {}
`,
		"bad/b_test.go": "package bad\n\nfunc helper() {}\n",
		"gen/gen.go":    "// Code generated by x. DO NOT EDIT.\n\npackage gen\n\nfunc g() {}\n",
	})

	var out, errw bytes.Buffer
	if code := run(root, []string{"./..."}, &out, &errw); code != 1 {
		t.Fatalf("exit %d, want 1\n%s%s", code, out.String(), errw.String())
	}
	want := []string{
		"bad/a.go:3: f has no doc comment",
		"bad/a.go:7: T.m has no doc comment",
		"bad/a.go:11: G.n has no doc comment",
		"bad/a.go:13: odd has no doc comment",
		"bad: package has no package comment",
	}
	got := strings.Split(strings.TrimSpace(out.String()), "\n")
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("got\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	if !strings.Contains(errw.String(), "5 problem(s)") {
		t.Errorf("stderr = %q", errw.String())
	}

	out.Reset()
	errw.Reset()
	if code := run(root, []string{"good", "gen"}, &out, &errw); code != 0 || out.Len() != 0 {
		t.Errorf("clean packages: exit %d, output %q %q", code, out.String(), errw.String())
	}
}

func TestRunError(t *testing.T) {
	t.Parallel()
	var out, errw bytes.Buffer
	if code := run(t.TempDir(), []string{"./..."}, &out, &errw); code != 2 || !strings.Contains(errw.String(), "doccheck:") {
		t.Errorf("exit %d, stderr %q; want 2 and an error", code, errw.String())
	}
}

// TestRepo runs the check over this repository, so a missing doc comment
// fails go test as well as CI.
func TestRepo(t *testing.T) {
	t.Parallel()
	var out, errw bytes.Buffer
	if code := run("../..", []string{"./..."}, &out, &errw); code != 0 {
		t.Errorf("doccheck found problems:\n%s", out.String())
	}
}
