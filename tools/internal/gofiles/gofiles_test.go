package gofiles

import (
	"errors"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

// writeTree creates files (path -> contents) under a new temp directory.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

var tree = map[string]string{
	"go.mod":                  "module example.com/m\n\ngo 1.27\n",
	"main.go":                 "package main\n",
	"main_test.go":            "package main\n",
	"README.md":               "hi\n",
	"a/a.go":                  "package a\n",
	"a/gen.go":                "// Code generated by hand. DO NOT EDIT.\n\npackage a\n",
	"a/b/b.go":                "package b\n",
	"a/testdata/t.go":         "package t\n",
	"a/.hidden/h.go":          "package h\n",
	"a/_skip/s.go":            "package s\n",
	"nested/go.mod":           "module example.com/nested\n",
	"nested/n.go":             "package n\n",
	"other/o.go":              "package o\n",
	"other/deeper/deeper.go":  "package deeper\n",
	"other/deeper/x_test.go":  "package deeper\n",
	"other/deeper/notgo.txt":  "x\n",
	"other/deeper/also.go.md": "x\n",
}

// collect walks root and returns the visited files' import paths, marking
// generated ones with a trailing " (gen)".
func collect(t *testing.T, root string, patterns ...string) []string {
	t.Helper()
	var got []string
	err := Walk(root, patterns, func(f File) error {
		s := f.ImportPath
		if f.Generated {
			s += " (gen)"
		}
		if f.AST == nil || f.Fset == nil || f.Path == "" {
			t.Errorf("incomplete File for %s", s)
		}
		got = append(got, s)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return got
}

func TestWalkPatterns(t *testing.T) {
	t.Parallel()
	root := writeTree(t, tree)
	cases := []struct {
		patterns []string
		want     []string
	}{
		{nil, []string{"example.com/m/main.go"}},
		{[]string{"."}, []string{"example.com/m/main.go"}},
		{[]string{"./..."}, []string{
			"example.com/m/a/a.go",
			"example.com/m/a/b/b.go",
			"example.com/m/a/gen.go (gen)",
			"example.com/m/main.go",
			"example.com/m/other/deeper/deeper.go",
			"example.com/m/other/o.go",
		}},
		{[]string{"a"}, []string{"example.com/m/a/a.go", "example.com/m/a/gen.go (gen)"}},
		{[]string{"./a/..."}, []string{"example.com/m/a/a.go", "example.com/m/a/b/b.go", "example.com/m/a/gen.go (gen)"}},
		{[]string{"..."}, nil}, // filled below: same as ./...
		{[]string{"a", "a/...", "a/b"}, []string{"example.com/m/a/a.go", "example.com/m/a/b/b.go", "example.com/m/a/gen.go (gen)"}},
	}
	cases[5].want = cases[2].want
	for _, c := range cases {
		if got := collect(t, root, c.patterns...); !reflect.DeepEqual(got, c.want) {
			t.Errorf("Walk(%q)\n got %q\nwant %q", c.patterns, got, c.want)
		}
	}
}

func TestWalkErrors(t *testing.T) {
	t.Parallel()
	nop := func(File) error { return nil }

	if err := Walk(t.TempDir(), nil, nop); err == nil {
		t.Error("missing go.mod: want error")
	}

	noModule := writeTree(t, map[string]string{"go.mod": "go 1.27\n"})
	if err := Walk(noModule, nil, nop); err == nil || !strings.Contains(err.Error(), "no module directive") {
		t.Errorf("go.mod without module: got %v", err)
	}

	root := writeTree(t, map[string]string{"go.mod": "module m\n", "bad/bad.go": "package\n", "ok/ok.go": "package ok\n"})
	if err := Walk(root, []string{"bad"}, nop); err == nil {
		t.Error("syntax error: want error")
	}
	if err := Walk(root, []string{"missing/..."}, nop); err == nil {
		t.Error("missing directory: want error")
	}

	stop := errors.New("stop")
	if err := Walk(root, []string{"ok"}, func(File) error { return stop }); !errors.Is(err, stop) {
		t.Errorf("callback error: got %v, want %v", err, stop)
	}
}

func TestModulePath(t *testing.T) {
	t.Parallel()
	root := writeTree(t, map[string]string{"go.mod": "// comment\nmodule \"example.com/quoted\" // trailing\n"})
	got, err := modulePath(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	if got != "example.com/quoted" {
		t.Errorf("modulePath = %q", got)
	}
}
