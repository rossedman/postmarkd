package main

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeTree creates files (path -> contents) under a new temp directory.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestRun(t *testing.T) {
	t.Parallel()
	root := writeTree(t, map[string]string{
		"go.mod":         "module example.com/m\n",
		"a/a.go":         "package a\n",
		"a/z.gen.go":     "// Code generated by oapi-codegen. DO NOT EDIT.\n\npackage a\n",
		"b/types.gen.go": "// Code generated by x. DO NOT EDIT.\n\npackage b\n",
		"b/not.go":       "// Code generated, but edited by hand.\n\npackage b\n",
	})
	var out, errw bytes.Buffer
	if code := run(root, []string{"./..."}, &out, &errw); code != 0 {
		t.Fatalf("exit %d: %s", code, errw.String())
	}
	want := "example.com/m/a/z.gen.go\nexample.com/m/b/types.gen.go\n"
	if out.String() != want {
		t.Errorf("got %q, want %q", out.String(), want)
	}
}

func TestRunError(t *testing.T) {
	t.Parallel()
	var out, errw bytes.Buffer
	if code := run(t.TempDir(), nil, &out, &errw); code != 2 || !strings.Contains(errw.String(), "generated:") {
		t.Errorf("exit %d, stderr %q; want 2 and an error", code, errw.String())
	}
}

// failWriter fails every write.
type failWriter struct{}

// Write always fails.
func (failWriter) Write([]byte) (int, error) { return 0, errors.New("broken pipe") }

func TestRunWriteError(t *testing.T) {
	t.Parallel()
	root := writeTree(t, map[string]string{
		"go.mod": "module m\n",
		"g.go":   "// Code generated by x. DO NOT EDIT.\n\npackage g\n",
	})
	var errw bytes.Buffer
	if code := run(root, nil, failWriter{}, &errw); code != 2 || !strings.Contains(errw.String(), "broken pipe") {
		t.Errorf("exit %d, stderr %q", code, errw.String())
	}
}
